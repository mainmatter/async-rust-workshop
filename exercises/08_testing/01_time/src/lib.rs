//! # Exercise
//!
//! The client connects once, and if nobody is listening yet it gives up and exits. Every real
//! client retries, and every retry that does not back off turns one restarting server into a
//! thundering herd.
//!
//! Write `with_backoff` in `src/retry.rs`. It runs an operation, and if that fails it waits and
//! runs it again, doubling the wait each time, until the operation works or the attempts run out.
//! The client binary already calls it, so once it compiles you can start the client first and the
//! server second and watch it connect.
//!
//! The signature is the interesting part:
//!
//! ```text
//! O: FnMut() -> F,
//! F: Future<Output = Result<T, E>>,
//! ```
//!
//! Not `FnMut() -> Result<T, E>`, and not a single future. A future runs once, so retrying means
//! asking for a _new_ one every time, which is why the argument is a closure that makes futures
//! rather than a future. This shape turns up everywhere in async Rust, in retry helpers, in
//! connection pools, in anything that supervises.
//!
//! What makes this chapter about testing is the tests. Four of them assert the exact wall-clock
//! time a retry sequence takes, up to fifteen hundred milliseconds of it, and the suite finishes in
//! microseconds because `start_paused` hands the clock to the runtime. There is no `sleep(2)` in
//! the test, no tolerance window, no flake on a loaded laptop: the assertion is `==`.
//!
//! That is the deal a paused clock offers. Code that waits by awaiting a timer is testable to the
//! millisecond. Code that waits any other way, in a blocking sleep or a spin loop, is not.

